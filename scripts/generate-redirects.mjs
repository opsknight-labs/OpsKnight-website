import fs from "node:fs";
import path from "node:path";

/**
 * Emit public/_redirects and public/_headers for Cloudflare Pages.
 *
 * A Next.js redirect() cannot be used here: the site is a static export, where
 * redirect() renders an error page rather than a redirect. Cloudflare Pages
 * applies _redirects natively, so the alias costs nothing at build or runtime.
 *
 * The newest version is derived from the content tree, so publishing docs/vX in
 * the app repo is still the only step — nothing here needs editing.
 *
 * Next static export writes RSC Flight payloads as .txt. Keep these files
 * available for client navigation; redirecting them to HTML breaks the router.
 */
const DOCS_ROOT = path.join(process.cwd(), "content", "docs");
const PUBLIC_DIR = path.join(process.cwd(), "public");

const isVersionDir = (name) => /^v\d+(\.\d+)*$/i.test(name);

const parse = (id) =>
  id
    .replace(/^v/i, "")
    .split(".")
    .map((s) => Number.parseInt(s, 10) || 0);

const newest = fs
  .readdirSync(DOCS_ROOT, { withFileTypes: true })
  .filter((e) => e.isDirectory() && isVersionDir(e.name))
  .map((e) => e.name)
  .sort((a, b) => {
    const [x, y] = [parse(a), parse(b)];
    for (let i = 0; i < Math.max(x.length, y.length); i += 1) {
      const diff = (y[i] ?? 0) - (x[i] ?? 0);
      if (diff !== 0) return diff;
    }
    return 0;
  })[0];

if (!newest) {
  console.warn("[redirects] no docs versions found; skipping _redirects");
  process.exit(0);
}

/** Every page slug in a version, mirroring the docs content loader. */
function slugsFor(version) {
  const root = path.join(DOCS_ROOT, version);
  const out = [];
  const walk = (dir, prefix) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (e.name.startsWith(".")) continue;
      const full = path.join(dir, e.name);
      if (e.isDirectory()) {
        walk(full, [...prefix, e.name]);
      } else if (e.name.endsWith(".md")) {
        const base = e.name.replace(/\.md$/, "");
        out.push(base.toUpperCase() === "README" ? prefix : [...prefix, base]);
      }
    }
  };
  walk(root, []);
  return out.filter((s) => s.length > 0);
}

/**
 * Flat aliases derived from the tree: integrations/communication/slack is also
 * reachable as integrations/slack and slack. Ambiguous names are skipped rather
 * than guessed at, and a real page always wins over an alias.
 */
function aliasesFor(version) {
  const slugs = slugsFor(version);
  const real = new Set(slugs.map((s) => s.join("/")));
  const candidates = new Map();
  for (const slug of slugs) {
    if (slug.length <= 2) continue;
    const full = slug.join("/");
    const leaf = slug[slug.length - 1];
    // Only the section-scoped form, e.g. integrations/datadog. A bare /datadog
    // alias for every page doubles the rule count for little gain, and the
    // budget below is tight.
    for (const alias of [`${slug[0]}/${leaf}`]) {
      if (alias === full || real.has(alias)) continue;
      candidates.set(alias, [...(candidates.get(alias) ?? []), full]);
    }
  }
  return [...candidates.entries()]
    .filter(([, targets]) => targets.length === 1)
    .map(([alias, targets]) => [alias, targets[0]]);
}

const versions = fs
  .readdirSync(DOCS_ROOT, { withFileTypes: true })
  .filter((e) => e.isDirectory() && isVersionDir(e.name))
  .map((e) => e.name);

// Cloudflare allows 2,000 static and 100 dynamic redirects independently.
const MAX_STATIC_RULES = 2000;
const header = [
  "# Generated by scripts/generate-redirects.mjs — do not edit by hand.",
  "# Keep RSC index.txt payloads intact for Next.js client navigation.",
];

const duplicateSegmentRules = [
  `/docs/:v/api/api/* /docs/:v/api/:splat 301`,
  `/docs/:v/integrations/apm-monitoring/apm-monitoring/* /docs/:v/integrations/apm-monitoring/:splat 301`,
  `/docs/:v/integrations/cloud/cloud/* /docs/:v/integrations/cloud/:splat 301`,
  `/docs/:v/integrations/metrics-alerting/metrics-alerting/* /docs/:v/integrations/metrics-alerting/:splat 301`,
  `/docs/:v/integrations/uptime/uptime/* /docs/:v/integrations/uptime/:splat 301`,
  `/docs/:v/integrations/ci-cd/ci-cd/* /docs/:v/integrations/ci-cd/:splat 301`,
  `/docs/:v/integrations/logs-events/logs-events/* /docs/:v/integrations/logs-events/:splat 301`,
  `/docs/:v/integrations/communication/communication/* /docs/:v/integrations/communication/:splat 301`,
  `/docs/:v/integrations/custom/custom/* /docs/:v/integrations/custom/:splat 301`,
  `/docs/:v/integrations/issue-tracking/issue-tracking/* /docs/:v/integrations/issue-tracking/:splat 301`,
  `/docs/:v/integrations/integrations/* /docs/:v/integrations/:splat 301`,
  `/docs/:v/getting-started/getting-started/* /docs/:v/getting-started/:splat 301`,
  `/docs/:v/getting-started/deployment/* /docs/:v/deployment/:splat 301`,
  `/docs/:v/core-concepts/core-concepts/* /docs/:v/core-concepts/:splat 301`,
  `/docs/:v/administration/administration/* /docs/:v/administration/:splat 301`,
  `/docs/:v/security/security/* /docs/:v/security/:splat 301`,
  `/docs/:v/deployment/deployment/* /docs/:v/deployment/:splat 301`,
];

const reserved = [
  "",
  "# Marketing route aliases",
  "/install /deploy/ 301",
  "/install/ /deploy/ 301",
  "/use-cases /solutions/ 301",
  "/use-cases/ /solutions/ 301",
  "",
  "# Section deduplication fixes",
  ...duplicateSegmentRules,
  "",
  "# Version-agnostic alias",
  `/docs/latest/* /docs/${newest}/:splat 302`,
  `/docs/latest /docs/${newest}/ 302`,
  `/docs /docs/${newest}/ 302`,
];

// Newest first so its aliases survive if the budget runs out
const ordered = [newest, ...versions.filter((v) => v !== newest)];
const aliasRules = [];
for (const version of ordered) {
  for (const [alias, target] of aliasesFor(version)) {
    aliasRules.push(
      `/docs/${version}/${alias}/ /docs/${version}/${target}/ 301`,
    );
  }
}

if (aliasRules.length > MAX_STATIC_RULES)
  throw Error("Cloudflare static redirect limit exceeded");
const rules = [
  ...header,
  ...reserved,
  "",
  "# Flat aliases for categorised pages",
  ...aliasRules,
];

const lines = rules.join("\n") + "\n";

fs.mkdirSync(PUBLIC_DIR, { recursive: true });
fs.writeFileSync(path.join(PUBLIC_DIR, "_redirects"), lines);

const headerLines = [
  "# Generated by scripts/generate-redirects.mjs — do not edit by hand.",
  "# Next.js static-export RSC payloads. Pretty HTML URLs must stay indexable;",
  "# these .txt files must not.",
  "",
];
for (let depth = 1; depth <= 8; depth += 1) {
  headerLines.push(`/${Array(depth).fill("*").join("/")}.txt`);
  headerLines.push("  X-Robots-Tag: noindex");
  headerLines.push("");
}
fs.writeFileSync(path.join(PUBLIC_DIR, "_headers"), headerLines.join("\n"));

console.log(`[redirects] /docs/latest -> /docs/${newest}`);
console.log("[headers] X-Robots-Tag: noindex on *.txt RSC payloads");
